//! A document's bibliography, read from its text: the generated block that
//! carries its cited entries, the `#bibliography` call, its style and its mode.

use crate::typst_source::{args_of, callee, dir_of, escape_string, quoted, relative, string, vault_path, walk};
use std::ops::Range;
use typst::syntax::ast::{AstNode, Str};
use typst::syntax::{LinkedNode, Source, SyntaxKind};

pub const LIBRARY_FILE: &str = "library.yaml";
const BLOCK_START: &str = "// thesio:bibliography:start";
const BLOCK_NOTE: &str = " (generated by Thesio: edits inside this block are overwritten)";
const BLOCK_END: &str = "// thesio:bibliography:end";

/// The citation styles offered per document: a label and Typst's name for it.
pub const CITATION_STYLES: [(&str, &str); 10] = [
    ("IEEE", "ieee"),
    ("APA", "apa"),
    ("Chicago (Author-Date)", "chicago-author-date"),
    ("Chicago (Notes)", "chicago-notes"),
    ("MLA", "mla"),
    ("Harvard", "harvard-cite-them-right"),
    ("Vancouver", "vancouver"),
    ("Nature", "nature"),
    ("ACM", "association-for-computing-machinery"),
    ("Springer", "springer-basic"),
];
/// What Typst uses for a `#bibliography` without a `style`.
pub const DEFAULT_STYLE: &str = "ieee";

/// How a document gets its bibliography.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    /// No `#bibliography` call.
    None,
    /// The generated block.
    Embedded,
    /// `#bibliography` pointing at `library.yaml`.
    Linked,
    /// A `#bibliography` the user wrote; Thesio changes it only on request.
    Custom,
}

/// The first `#bibliography` call under `root`.
fn first_call<'a>(root: &LinkedNode<'a>) -> Option<LinkedNode<'a>> {
    let mut found = None;
    walk(root, &mut |node| {
        if found.is_none() && node.kind() == SyntaxKind::FuncCall && callee(node).as_deref() == Some("bibliography") { found = Some(node.clone()); }
    });
    found
}

/// The vault path of a call's source, when it names exactly one. `sources`
/// may also be an array of paths.
fn source_path(call: &LinkedNode, file: &str) -> Option<String> {
    let args = args_of(call)?;
    let mut sources = args.children().flat_map(|arg| if arg.kind() == SyntaxKind::Array { arg.children().collect() } else { vec![arg] })
        .filter(|arg| arg.kind() == SyntaxKind::Str);
    let source = sources.next().filter(|_| sources.next().is_none())?;
    vault_path(&dir_of(file), &string(&source)?)
}

fn is_linked(call: &LinkedNode, file: &str) -> bool { source_path(call, file).as_deref() == Some(LIBRARY_FILE) }

/// The string given for a call's `style` argument.
fn style_value<'a>(args: &LinkedNode<'a>) -> Option<LinkedNode<'a>> {
    let named = args.children().filter(|child| child.kind() == SyntaxKind::Named)
        .find(|child| child.children().next().is_some_and(|name| name.get().full_text() == "style"))?;
    named.children().find(|child| child.kind() == SyntaxKind::Str)
}

/// The `style` a document's `#bibliography` asks for.
pub fn style(text: &str) -> Option<String> {
    let source = Source::detached(text);
    let value = style_value(&args_of(&first_call(&LinkedNode::new(source.root()))?)?)?;
    Str::from_untyped(value.get()).map(|value| value.get().to_string())
}

/// `text` with its `#bibliography` using `style`.
pub fn set_style(text: &str, style: &str) -> Option<String> {
    let source = Source::detached(text);
    let args = args_of(&first_call(&LinkedNode::new(source.root()))?)?;
    let literal = quoted(style);
    if let Some(value) = style_value(&args) {
        return Some(format!("{}{literal}{}", &text[..value.range().start], &text[value.range().end..]));
    }
    // Before the closing parenthesis, which a trailing comma may precede.
    let close = args.range().end - 1;
    let head = text[..close].trim_end();
    let separator = if head.ends_with('(') { "" } else if head.ends_with(',') { " " } else { ", " };
    Some(format!("{head}{separator}style: {literal}{}", &text[close..]))
}

pub fn mode(text: &str, file: &str) -> Mode {
    if block_range(text).is_some() { return Mode::Embedded; }
    let source = Source::detached(text);
    match first_call(&LinkedNode::new(source.root())) {
        None => Mode::None,
        Some(call) if is_linked(&call, file) => Mode::Linked,
        Some(_) => Mode::Custom,
    }
}

/// The bytes of a document's generated block, with its final newline.
pub fn block_range(text: &str) -> Option<Range<usize>> {
    let start = text.find(BLOCK_START)?;
    let end = start + text[start..].find(BLOCK_END)? + BLOCK_END.len();
    let end = if text[end..].starts_with('\n') { end + 1 } else { end };
    Some(start..end)
}

/// Text after the data in an existing block, such as `, style: "ieee"`.
fn block_options(block: &str) -> String {
    let source = Source::detached(block);
    let options = || {
        let args = args_of(&first_call(&LinkedNode::new(source.root()))?)?;
        let data = args.children().find(|arg| arg.kind() == SyntaxKind::FuncCall && callee(arg).as_deref() == Some("bytes"))?;
        Some(block[data.range().end..args.range().end - 1].to_string())
    };
    options().unwrap_or_default()
}

fn render_block(yaml: &str, options: &str) -> String {
    let data = escape_string(yaml);
    let data = if data.is_empty() { "{}\n".to_string() } else { data };
    format!("{BLOCK_START}{BLOCK_NOTE}\n#bibliography(bytes(\"\n{data}\"){options})\n{BLOCK_END}\n")
}

/// A document's text without its generated block, for previews and search.
pub fn without_block(text: &str) -> String {
    match block_range(text) {
        Some(range) => format!("{}{}", &text[..range.start], &text[range.end..]),
        None => text.to_string(),
    }
}

/// `text` with its generated block holding `yaml`, or `None` when unchanged.
pub fn sync_block(text: &str, yaml: &str) -> Option<String> {
    let range = block_range(text)?;
    let block = render_block(yaml, &block_options(&text[range.clone()]));
    (text[range.clone()] != *block).then(|| format!("{}{block}{}", &text[..range.start], &text[range.end..]))
}

/// `text` followed by `tail`, a blank line apart.
fn append(text: &str, tail: &str) -> String {
    let separator = if text.is_empty() || text.ends_with("\n\n") { "" } else if text.ends_with('\n') { "\n" } else { "\n\n" };
    format!("{text}{separator}{tail}")
}

/// `text` with a generated block added at the end.
pub fn embed(text: &str, yaml: &str) -> String {
    append(text, &render_block(yaml, ""))
}

/// `text` with a `#bibliography` line for the library added at the end.
pub fn link(text: &str, file: &str) -> String {
    append(text, &format!("#bibliography({})\n", quoted(&relative(&dir_of(file), LIBRARY_FILE))))
}

/// `text` without its generated block or linked `#bibliography` line. A
/// bibliography the user wrote stays.
pub fn remove(text: &str, file: &str) -> String {
    if let Some(range) = block_range(text) {
        return format!("{}{}", text[..range.start].trim_end_matches('\n').to_string() + "\n", &text[range.end..]);
    }
    let source = Source::detached(text);
    let Some(call) = first_call(&LinkedNode::new(source.root())).filter(|call| is_linked(call, file)) else { return text.to_string() };
    let start = text[..call.range().start].rfind('\n').map_or(0, |i| i + 1);
    let end = text[call.range().end..].find('\n').map_or(text.len(), |i| call.range().end + i + 1);
    format!("{}{}", &text[..start], &text[end..])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_offered_style_exists() {
        for (_, style) in CITATION_STYLES { assert!(hayagriva::archive::ArchivedStyle::by_name(style).is_some(), "{style}"); }
    }

    #[test]
    fn a_block_keeps_its_style_when_the_library_changes() {
        let text = embed("Text\n", "a:\n  type: Book\n");
        let styled = set_style(&text, "apa").unwrap();
        assert_eq!(style(&styled).as_deref(), Some("apa"));
        let synced = sync_block(&styled, "b:\n  type: Book\n").unwrap();
        assert_eq!(style(&synced).as_deref(), Some("apa"));
        assert!(synced.contains("b:\n"));
        let again = set_style(&synced, "mla").unwrap();
        assert_eq!(style(&again).as_deref(), Some("mla"));
        assert_eq!(mode(&again, "doc.typ"), Mode::Embedded);
    }

    #[test]
    fn a_block_keeps_options_that_span_lines() {
        let text = embed("", "a:\n  type: Book\n").replace("\"))\n// thesio", "\"),\n  title: [Sources],\n)\n// thesio");
        assert!(text.contains("\n  title: [Sources],\n)"), "{text}");
        assert!(sync_block(&text, "b:\n  type: Book\n").unwrap().contains("title: [Sources]"));
    }

    #[test]
    fn a_written_bibliography_keeps_its_other_arguments() {
        let text = "#bibliography(\"/refs.bib\", title: [Literatur], style: \"ieee\")\n";
        assert_eq!(set_style(text, "apa").unwrap(), "#bibliography(\"/refs.bib\", title: [Literatur], style: \"apa\")\n");
        assert_eq!(set_style("#bibliography(\"a.bib\",)", "apa").unwrap(), "#bibliography(\"a.bib\", style: \"apa\")");
    }

    #[test]
    fn a_bibliography_the_user_wrote_is_left_alone() {
        let custom = "Text\n#bibliography(\"refs.bib\")\n";
        assert_eq!(mode(custom, "doc.typ"), Mode::Custom);
        assert_eq!(remove(custom, "doc.typ"), custom);
        let several = "#bibliography((\"library.yaml\", \"refs.bib\"))\n";
        assert_eq!(mode(several, "doc.typ"), Mode::Custom);
        assert_eq!(remove(several, "doc.typ"), several);
        assert_eq!(mode("#bibliography(\"https://x.org/library.yaml\")", "doc.typ"), Mode::Custom);
        let linked = link("Text\n", "ch/doc.typ");
        assert_eq!(mode(&linked, "ch/doc.typ"), Mode::Linked);
        assert_eq!(remove(&linked, "ch/doc.typ"), "Text\n\n");
    }

    #[test]
    fn a_quote_in_a_style_stays_inside_its_string() {
        assert_eq!(set_style("#bibliography(\"a.bib\")", "a\"b").unwrap(), "#bibliography(\"a.bib\", style: \"a\\\"b\")");
    }
}
