//! The citation library: Hayagriva entries in `library.yaml` at the vault root.
//! The YAML mapping is the source of truth, so editing an entry keeps every
//! field the form does not show. Also the generated bibliography block that
//! carries a document's cited entries inside the document itself.

use crate::lookup::{Identifier, PaperIds};
use crate::references::{self, BibliographyCall};
use crate::store::{natural_cmp, write_atomic};
use anyhow::{Context, Result};
use hayagriva::types::EntryType;
use serde_yaml::{Mapping, Value};
use std::collections::BTreeSet;
use std::ops::Range;
use std::path::{Path, PathBuf};

pub const LIBRARY_FILE: &str = "library.yaml";
/// The vault folder that holds downloaded papers.
pub const PAPERS_DIR: &str = "sources";

/// The vault path of the paper for `key`. Keys may hold characters a file name should not.
/// The vault folder that holds notes on sources.
pub const NOTES_DIR: &str = "notes";

/// The notes document that goes with paper `id`, or with `paper_file(key)`.
pub fn note_file(paper: &str) -> String {
    let name = paper.rsplit('/').next().unwrap_or(paper);
    format!("{NOTES_DIR}/{}.typ", name.strip_suffix(".pdf").unwrap_or(name))
}

pub fn paper_file(key: &str) -> String {
    let stem: String = key.chars().map(|c| if c.is_alphanumeric() || matches!(c, '-' | '_' | '.') { c } else { '-' }).collect();
    format!("{PAPERS_DIR}/{}.pdf", stem.trim_start_matches('.'))
}
const BLOCK_START: &str = "// thesio:bibliography:start";
const BLOCK_NOTE: &str = " (generated by Thesio: edits inside this block are overwritten)";
const BLOCK_END: &str = "// thesio:bibliography:end";

/// A table row.
#[derive(Clone, Debug)]
pub struct Row {
    pub key: String,
    pub kind: String,
    pub title: String,
    pub authors: String,
    pub year: String,
}

/// The fields the entry form edits, as plain text.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Fields {
    pub key: String,
    pub kind: String,
    pub title: String,
    /// `Family, Given; Family, Given`
    pub authors: String,
    pub year: String,
    /// The journal, book, or other work this was published in.
    pub container: String,
    pub publisher: String,
    pub volume: String,
    pub pages: String,
    pub doi: String,
    pub url: String,
}

/// How a document gets its bibliography.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    /// No `#bibliography` call.
    None,
    /// The generated block.
    Embedded,
    /// `#bibliography` pointing at `library.yaml`.
    Linked,
    /// A `#bibliography` the user wrote; Thesio leaves it alone.
    Custom,
}

/// The outcome of adding a looked-up entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Added {
    New(String),
    /// It was in the library already, under this key.
    Duplicate(String),
}

pub struct Library {
    path: PathBuf,
    entries: Mapping,
    parsed: hayagriva::Library,
}

fn yaml_error(path: &Path, error: impl std::fmt::Display) -> anyhow::Error {
    anyhow::anyhow!("{} is not a valid library: {error}", path.display())
}

fn set(map: &mut Mapping, key: &str, value: Option<Value>) {
    match value {
        Some(value) => { map.insert(key.into(), value); }
        None => { map.remove(key); }
    }
}

fn text_value(text: &str) -> Option<Value> {
    let text = text.trim();
    (!text.is_empty()).then(|| text.into())
}

impl Library {
    /// Reads the vault's library. A file that does not parse is an error, so
    /// that nothing overwrites it.
    pub fn load(root: &Path) -> Result<Self> {
        let path = root.join(LIBRARY_FILE);
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
            Err(e) => return Err(e).with_context(|| format!("Could not read {}", path.display())),
        };
        Self::parse(path, &text)
    }

    fn parse(path: PathBuf, text: &str) -> Result<Self> {
        let entries: Mapping = match serde_yaml::from_str::<Option<Mapping>>(text) {
            Ok(entries) => entries.unwrap_or_default(),
            Err(e) => return Err(yaml_error(&path, e)),
        };
        let parsed = if entries.is_empty() { hayagriva::Library::new() } else { hayagriva::io::from_yaml_str(text).map_err(|e| yaml_error(&path, e))? };
        Ok(Self { path, entries, parsed })
    }

    /// Validates `entries` with Hayagriva, then writes them.
    fn commit(&mut self, entries: Mapping) -> Result<()> {
        let text = if entries.is_empty() { String::new() } else { serde_yaml::to_string(&entries)? };
        let next = Self::parse(self.path.clone(), &text)?;
        write_atomic(&self.path, text.as_bytes())?;
        *self = next;
        Ok(())
    }

    pub fn len(&self) -> usize { self.parsed.len() }
    pub fn is_empty(&self) -> bool { self.parsed.is_empty() }
    pub fn contains(&self, key: &str) -> bool { self.parsed.get(key).is_some() }

    /// What the paper of `key` can be found by.
    pub fn paper_ids(&self, key: &str) -> PaperIds {
        let Some(fields) = self.fields(key) else { return PaperIds::default() };
        let serial = |kind: &str| self.entries.get(key)?.get("serial-number")?.get(kind)?.as_str().map(str::to_string);
        let from_url = match crate::lookup::identify(&fields.url) {
            Some(Identifier::Arxiv(id)) => Some(id),
            _ => None,
        };
        PaperIds { doi: Some(fields.doi).filter(|doi| !doi.is_empty()), arxiv: serial("arxiv").or(from_url) }
    }

    pub fn rows(&self) -> Vec<Row> {
        self.parsed.iter().map(|entry| Row {
            key: entry.key().to_string(),
            kind: format!("{:?}", entry.entry_type()),
            title: entry.title().map(|t| t.to_string()).unwrap_or_default(),
            authors: entry.authors().unwrap_or_default().iter().map(|p| p.name.clone()).collect::<Vec<_>>().join(", "),
            year: entry.date_any().map(|d| d.year.to_string()).unwrap_or_default(),
        }).collect()
    }

    /// The form's view of an entry.
    pub fn fields(&self, key: &str) -> Option<Fields> {
        let entry = self.parsed.get(key)?;
        let raw = self.entries.get(key)?;
        let text = |name: &str| raw.get(name).map(|v| match v {
            Value::String(s) => s.clone(),
            Value::Number(n) => n.to_string(),
            _ => String::new(),
        }).unwrap_or_default();
        // Imported articles keep their volume on the journal.
        let parent_text = |name: &str| {
            let own = text(name);
            if !own.is_empty() { return own; }
            match raw.get("parent").and_then(|p| p.get(name)) {
                Some(Value::String(s)) => s.clone(),
                Some(Value::Number(n)) => n.to_string(),
                _ => String::new(),
            }
        };
        let persons = entry.authors().unwrap_or_default().iter().map(|p| match &p.given_name {
            Some(given) => format!("{}, {given}", p.name),
            None => p.name.clone(),
        }).collect::<Vec<_>>().join("; ");
        Some(Fields {
            key: key.to_string(),
            kind: format!("{:?}", entry.entry_type()),
            title: entry.title().map(|t| t.to_string()).unwrap_or_default(),
            authors: persons,
            year: entry.date_any().map(|d| d.year.to_string()).unwrap_or_default(),
            container: entry.parents().first().and_then(|p| p.title()).map(|t| t.to_string()).unwrap_or_default(),
            publisher: entry.publisher().and_then(|p| p.name()).map(|n| n.to_string()).unwrap_or_default(),
            volume: parent_text("volume"),
            pages: text("page-range"),
            doi: entry.doi().unwrap_or_default().to_string(),
            url: entry.url_any().map(|u| u.value.to_string()).unwrap_or_default(),
        })
    }

    /// Adds an entry, or updates `original` and keeps the fields the form
    /// does not show. Entries that would not parse are rejected unwritten.
    pub fn save_entry(&mut self, original: Option<&str>, fields: &Fields) -> Result<()> {
        let key = fields.key.trim();
        anyhow::ensure!(!key.is_empty(), "Enter a citation key");
        anyhow::ensure!(!key.contains(char::is_whitespace), "Citation keys cannot contain spaces");
        anyhow::ensure!(original == Some(key) || !self.contains(key), "{key} is already in the library");
        let mut map = original.and_then(|k| self.entries.get(k)).and_then(Value::as_mapping).cloned().unwrap_or_default();
        let kind = if fields.kind.trim().is_empty() { "Misc" } else { fields.kind.trim() };
        set(&mut map, "type", Some(kind.into()));
        set(&mut map, "title", text_value(&fields.title));
        let authors: Vec<Value> = fields.authors.split(';').filter_map(text_value).collect();
        set(&mut map, "author", (!authors.is_empty()).then(|| Value::Sequence(authors)));
        // Dates carry more than the form's year: keep one that already matches.
        let same_year = self.parsed.get(original.unwrap_or_default()).and_then(|e| e.date_any()).is_some_and(|d| d.year.to_string() == fields.year.trim());
        if !same_year { set(&mut map, "date", text_value(&fields.year).map(|y| y.as_str().and_then(|y| y.parse::<i64>().ok()).map_or(y.clone(), Value::from))); }
        set(&mut map, "publisher", text_value(&fields.publisher));
        set(&mut map, "page-range", text_value(&fields.pages));
        set(&mut map, "url", text_value(&fields.url));
        let parent = map.get("parent").and_then(Value::as_mapping).cloned();
        let default_parent = if kind.eq_ignore_ascii_case("article") { "Periodical" } else { "Book" };
        set(&mut map, "parent", text_value(&fields.container).map(|title| {
            let mut parent = parent.unwrap_or_else(|| { let mut m = Mapping::new(); m.insert("type".into(), default_parent.into()); m });
            parent.insert("title".into(), title);
            Value::Mapping(parent)
        }));
        let volume_on_parent = map.get("parent").and_then(|p| p.get("volume")).is_some();
        match map.get_mut("parent").and_then(Value::as_mapping_mut).filter(|_| volume_on_parent) {
            Some(parent) => set(parent, "volume", text_value(&fields.volume)),
            None => set(&mut map, "volume", text_value(&fields.volume)),
        }
        let mut serial = map.get("serial-number").and_then(Value::as_mapping).cloned().unwrap_or_default();
        set(&mut serial, "doi", text_value(&fields.doi));
        set(&mut map, "serial-number", (!serial.is_empty()).then(|| Value::Mapping(serial)));
        let mut entries = Mapping::new();
        let mut placed = false;
        for (k, v) in &self.entries {
            if Some(k.as_str().unwrap_or_default()) == original {
                entries.insert(key.into(), Value::Mapping(map.clone()));
                placed = true;
            } else {
                entries.insert(k.clone(), v.clone());
            }
        }
        if !placed { entries.insert(key.into(), Value::Mapping(map)); }
        self.commit(entries)
    }

    pub fn delete_entry(&mut self, key: &str) -> Result<()> {
        let mut entries = self.entries.clone();
        entries.remove(key);
        self.commit(entries)
    }

    /// Imports BibLaTeX text. Keys already in the library are kept as they
    /// are. Returns the number of entries added and skipped.
    pub fn import_biblatex(&mut self, text: &str) -> Result<(usize, usize)> {
        let library = hayagriva::io::from_biblatex_str(text).map_err(|errors| {
            anyhow::anyhow!(errors.iter().map(|e| e.to_string()).collect::<Vec<_>>().join("; "))
        })?;
        let incoming: Mapping = serde_yaml::from_str(&hayagriva::io::to_yaml_str(&library)?)?;
        let mut entries = self.entries.clone();
        let (mut added, mut skipped) = (0, 0);
        for (key, value) in incoming {
            if entries.contains_key(&key) {
                skipped += 1;
            } else {
                entries.insert(key, value);
                added += 1;
            }
        }
        if added > 0 { self.commit(entries)?; }
        Ok((added, skipped))
    }

    /// Adds a looked-up entry under a generated key, unless an entry with the
    /// same DOI, PMID, ISBN, or arXiv ID is here already.
    pub fn add_fetched(&mut self, mut entry: Mapping) -> Result<Added> {
        if let Some(key) = self.find_duplicate(&entry) { return Ok(Added::Duplicate(key)); }
        let key = self.fresh_key(&entry);
        if !entry.contains_key("type") { entry.insert("type".into(), "Misc".into()); }
        let mut entries = self.entries.clone();
        entries.insert(key.as_str().into(), Value::Mapping(entry));
        self.commit(entries)?;
        Ok(Added::New(key))
    }

    fn find_duplicate(&self, entry: &Mapping) -> Option<String> {
        let numbers = |map: &Mapping| -> Vec<(String, String)> {
            map.get("serial-number").and_then(Value::as_mapping).map_or(vec![], |serial| serial.iter().filter_map(|(kind, value)| {
                Some((kind.as_str()?.to_lowercase(), value.as_str()?.to_lowercase()))
            }).collect())
        };
        let wanted = numbers(entry);
        self.entries.iter().find(|(_, existing)| existing.as_mapping().is_some_and(|map| numbers(map).iter().any(|n| wanted.contains(n)))).and_then(|(key, _)| key.as_str()).map(str::to_string)
    }

    /// `surname` + `year`, with a letter added when the key is taken.
    fn fresh_key(&self, entry: &Mapping) -> String {
        let person = match entry.get("author") {
            Some(Value::Sequence(list)) => list.first(),
            other => other,
        };
        let name = match person {
            Some(Value::Mapping(map)) => map.get("name").and_then(Value::as_str),
            other => other.and_then(Value::as_str),
        };
        let surname = name.and_then(|n| n.split(',').next()).and_then(|n| n.split_whitespace().next_back()).map_or(String::new(), ascii_key);
        let year = entry.get("date").map(|date| match date {
            Value::Number(n) => n.to_string(),
            Value::String(s) => s.chars().take(4).collect(),
            _ => String::new(),
        }).unwrap_or_default();
        let base = match (surname.is_empty(), year.is_empty()) {
            (true, true) => "entry".to_string(),
            (true, false) => format!("entry{year}"),
            _ => format!("{surname}{year}"),
        };
        if !self.contains(&base) { return base; }
        ('b'..='z').map(|letter| format!("{base}{letter}")).find(|key| !self.contains(key))
            .unwrap_or_else(|| (2..).map(|n| format!("{base}-{n}")).find(|key| !self.contains(key)).unwrap_or(base))
    }

    /// The whole library as BibLaTeX. Fields BibLaTeX has no place for are
    /// left out.
    pub fn export_biblatex(&self) -> String {
        let mut rows: Vec<&hayagriva::Entry> = self.parsed.iter().collect();
        rows.sort_by(|a, b| natural_cmp(a.key(), b.key()));
        rows.into_iter().map(biblatex_entry).collect::<Vec<_>>().join("\n")
    }

    /// YAML for the entries in `keys`, in library order.
    pub fn subset(&self, keys: &BTreeSet<String>) -> Result<String> {
        let entries: Mapping = self.entries.iter().filter(|(k, _)| k.as_str().is_some_and(|k| keys.contains(k))).map(|(k, v)| (k.clone(), v.clone())).collect();
        Ok(if entries.is_empty() { String::new() } else { serde_yaml::to_string(&entries)? })
    }
}

/// Lowercase ASCII for a citation key, folding common accented letters.
fn ascii_key(text: &str) -> String {
    let mut key = String::new();
    for c in text.chars().flat_map(char::to_lowercase) {
        match c {
            'ä' | 'æ' => key.push_str("ae"),
            'ö' | 'œ' => key.push_str("oe"),
            'ü' => key.push_str("ue"),
            'ß' => key.push_str("ss"),
            'à' | 'á' | 'â' | 'ã' | 'å' => key.push('a'),
            'ç' | 'č' | 'ć' => key.push('c'),
            'è' | 'é' | 'ê' | 'ë' => key.push('e'),
            'ì' | 'í' | 'î' | 'ï' => key.push('i'),
            'ñ' | 'ń' => key.push('n'),
            'ò' | 'ó' | 'ô' | 'õ' | 'ø' => key.push('o'),
            'š' | 'ś' => key.push('s'),
            'ù' | 'ú' | 'û' => key.push('u'),
            'ý' | 'ÿ' => key.push('y'),
            'ž' | 'ź' => key.push('z'),
            c if c.is_ascii_alphanumeric() => key.push(c),
            _ => {}
        }
    }
    key
}

fn biblatex_kind(entry: &hayagriva::Entry) -> &'static str {
    let parent = entry.parents().first().map(|p| p.entry_type());
    match entry.entry_type() {
        EntryType::Article => if matches!(parent, Some(EntryType::Conference | EntryType::Proceedings)) { "inproceedings" } else { "article" },
        EntryType::Book => "book",
        EntryType::Chapter => "inbook",
        EntryType::Anthos => "incollection",
        EntryType::Anthology => "collection",
        EntryType::Proceedings => "proceedings",
        EntryType::Report => "report",
        EntryType::Thesis => "thesis",
        EntryType::Web => "online",
        EntryType::Manuscript => "unpublished",
        EntryType::Patent => "patent",
        _ => "misc",
    }
}

fn biblatex_entry(entry: &hayagriva::Entry) -> String {
    let escape = |text: &str| text.replace('{', "\\{").replace('}', "\\}");
    let mut fields: Vec<(&str, String)> = vec![];
    if let Some(title) = entry.title() { fields.push(("title", title.to_string())); }
    if let Some(authors) = entry.authors() {
        let names = authors.iter().map(|p| match &p.given_name {
            Some(given) => format!("{}, {given}", p.name),
            None => p.name.clone(),
        }).collect::<Vec<_>>().join(" and ");
        fields.push(("author", names));
    }
    if let Some(date) = entry.date_any() {
        let mut text = format!("{:04}", date.year);
        if let Some(month) = date.month { text += &format!("-{:02}", month + 1); }
        fields.push(("date", text));
    }
    if let Some(parent) = entry.parents().first().and_then(|p| p.title()) {
        let name = if biblatex_kind(entry) == "article" { "journaltitle" } else { "booktitle" };
        fields.push((name, parent.to_string()));
    }
    if let Some(publisher) = entry.publisher().and_then(|p| p.name()) { fields.push(("publisher", publisher.to_string())); }
    if let Some(volume) = entry.volume().or_else(|| entry.parents().first().and_then(|p| p.volume())) { fields.push(("volume", volume.to_string())); }
    if let Some(issue) = entry.issue().or_else(|| entry.parents().first().and_then(|p| p.issue())) { fields.push(("number", issue.to_string())); }
    if let Some(pages) = entry.page_range() { fields.push(("pages", pages.to_string())); }
    if let Some(doi) = entry.doi() { fields.push(("doi", doi.to_string())); }
    if let Some(url) = entry.url_any() { fields.push(("url", url.value.to_string())); }
    let body = fields.iter().map(|(name, value)| format!("  {name} = {{{}}},", escape(value))).collect::<Vec<_>>().join("\n");
    format!("@{}{{{},\n{body}\n}}\n", biblatex_kind(entry), entry.key())
}

/// The bytes of a document's generated block, with its final newline.
pub fn block_range(text: &str) -> Option<Range<usize>> {
    let start = text.find(BLOCK_START)?;
    let end = start + text[start..].find(BLOCK_END)? + BLOCK_END.len();
    let end = if text[end..].starts_with('\n') { end + 1 } else { end };
    Some(start..end)
}

/// Text after the data in an existing block, such as `, style: "ieee"`.
fn block_options(block: &str) -> &str {
    block.lines().rev().find_map(|line| line.strip_prefix("\")")?.strip_suffix(')')).unwrap_or("")
}

fn render_block(yaml: &str, options: &str) -> String {
    let data = yaml.replace('\\', "\\\\").replace('"', "\\\"");
    let data = if data.is_empty() { "{}\n".to_string() } else { data };
    format!("{BLOCK_START}{BLOCK_NOTE}\n#bibliography(bytes(\"\n{data}\"){options})\n{BLOCK_END}\n")
}

/// A document's text without its generated block, for previews and search.
pub fn without_block(text: &str) -> String {
    match block_range(text) {
        Some(range) => format!("{}{}", &text[..range.start], &text[range.end..]),
        None => text.to_string(),
    }
}

pub fn mode(text: &str, file: &str) -> Mode {
    if block_range(text).is_some() { return Mode::Embedded; }
    match references::bibliography_call(text, file) {
        None => Mode::None,
        Some(BibliographyCall { path: Some(path), .. }) if path == LIBRARY_FILE => Mode::Linked,
        Some(_) => Mode::Custom,
    }
}

/// `text` with its generated block holding `yaml`, or `None` when unchanged.
pub fn sync_block(text: &str, yaml: &str) -> Option<String> {
    let range = block_range(text)?;
    let block = render_block(yaml, block_options(&text[range.clone()]));
    (text[range.clone()] != *block).then(|| format!("{}{block}{}", &text[..range.start], &text[range.end..]))
}

/// `text` with a generated block added at the end.
pub fn embed(text: &str, yaml: &str) -> String {
    let separator = if text.is_empty() || text.ends_with("\n\n") { "" } else if text.ends_with('\n') { "\n" } else { "\n\n" };
    format!("{text}{separator}{}", render_block(yaml, ""))
}

/// `text` with a `#bibliography` line for the library added at the end.
pub fn link(text: &str, file: &str) -> String {
    let separator = if text.is_empty() || text.ends_with("\n\n") { "" } else if text.ends_with('\n') { "\n" } else { "\n\n" };
    format!("{text}{separator}#bibliography(\"{}\")\n", references::relative_to(file, LIBRARY_FILE))
}

/// `text` without its generated block or linked `#bibliography` line.
pub fn remove(text: &str, file: &str) -> String {
    if let Some(range) = block_range(text) {
        return format!("{}{}", text[..range.start].trim_end_matches('\n').to_string() + "\n", &text[range.end..]);
    }
    let Some(call) = references::bibliography_call(text, file) else { return text.to_string() };
    let start = text[..call.range.start].rfind('\n').map_or(0, |i| i + 1);
    let end = text[call.range.end..].find('\n').map_or(text.len(), |i| call.range.end + i + 1);
    format!("{}{}", &text[..start], &text[end..])
}

pub const BLOCK_MARKER: &str = BLOCK_START;
